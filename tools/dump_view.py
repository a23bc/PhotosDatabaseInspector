def block(title, keys):
    print("\n== %s ==" % title)
    for a in assets:
        f = flatten(a)
        print("-- %s  %s" % (a["pk"], a["filename"]))
        for k in keys:
            if k in f:
                print("   %-52s = %s" % (k, f[k]))


